#!/usr/bin/env python3
"""Generate MainUI widget YAML from the canonical file; --check never writes."""
import argparse
from pathlib import Path

import yaml

class Dumper(yaml.SafeDumper):
    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


ROOT = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if imports differ from source')
    args = parser.parse_args()
    source = yaml.safe_load((ROOT / 'bmw-vehicle-widgets.yml').read_text())
    stale = []
    for uid, widget in source['widgets'].items():
        path = ROOT / 'imports' / f'{uid}.yaml'
        content = '# Generated by openHAB/generate_imports.py; edit the canonical source.\n'
        content += yaml.dump({'uid': uid, **widget}, Dumper=Dumper, sort_keys=False, allow_unicode=True, width=160)
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        parser.exit(1, 'Outdated imports: ' + ', '.join(stale) + '\n')


if __name__ == '__main__':
    main()
